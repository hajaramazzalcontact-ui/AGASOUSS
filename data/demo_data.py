def load_demo_data():
    """
    Charge toutes les données de démonstration dans la base de données
    """
    from data.database import SessionLocal
    from data.models import Activity, Restaurant, Accommodation, Transport, Spot, Review
    
    db = SessionLocal()
    
    try:
        # Charger activités
        for act_data in DEMO_ACTIVITIES:
            existing = db.query(Activity).filter(Activity.id == act_data["id"]).first()
            if not existing:
                activity = Activity(**act_data)
                db.add(activity)
        
        # Charger restaurants
        for rest_data in DEMO_RESTAURANTS:
            existing = db.query(Restaurant).filter(Restaurant.id == rest_data["id"]).first()
            if not existing:
                restaurant = Restaurant(**rest_data)
                db.add(restaurant)
        
        # Charger hébergements
        for acc_data in DEMO_ACCOMMODATIONS:
            existing = db.query(Accommodation).filter(Accommodation.id == acc_data["id"]).first()
            if not existing:
                accommodation = Accommodation(**acc_data)
                db.add(accommodation)
        
        # Charger transports
        for trans_data in DEMO_TRANSPORTS:
            existing = db.query(Transport).filter(Transport.id == trans_data["id"]).first()
            if not existing:
                transport = Transport(**trans_data)
                db.add(transport)
        
        # Charger spots
        for spot_data in DEMO_SPOTS:
            existing = db.query(Spot).filter(Spot.id == spot_data["id"]).first()
            if not existing:
                spot = Spot(**spot_data)
                db.add(spot)
        
        # Charger avis (avec mise à jour des ratings)
        for rev_data in DEMO_REVIEWS:
            existing = db.query(Review).filter(Review.id == rev_data["id"]).first()
            if not existing:
                review = Review(**rev_data)
                db.add(review)
        
        db.commit()
        print("✅ Données de démonstration chargées avec succès")
        
    except Exception as e:
        db.rollback()
        print(f"❌ Erreur lors du chargement des données : {e}")
    finally:
        db.close()
